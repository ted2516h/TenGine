// TenGine.js
//
// Tiled 1.12.2
// Export Tiled tile map to TenGine/Picotron Lua format.

var TenGineMapFormat = {
    name: "TenGine Map",
    extension: "lua",

    write: function(map, fileName) {

        // 只支持普通有限地图
        if (map.infinite) {
            return "TenGine Map does not support infinite maps.";
        }

        var output = "";

        // --------------------------------------------------
        // Map information
        // --------------------------------------------------

        output += "-- TenGine Map\n";
        output += "-- Generated by Tiled\n\n";

        output += "MapWidth = " + map.width + "\n";
        output += "MapHeight = " + map.height + "\n";
        output += "MapTileWidth = " + map.tileWidth + "\n";
        output += "MapTileHeight = " + map.tileHeight + "\n\n";


        // --------------------------------------------------
        // Find all tile layers
        // --------------------------------------------------

        var tileLayers = [];

        for (var i = 0; i < map.layerCount; ++i) {

            var layer = map.layerAt(i);

            if (layer.isTileLayer) {
                tileLayers.push(layer);
            }

        }

        if (tileLayers.length === 0) {
            return "TenGine Map requires at least one tile layer.";
        }


        // --------------------------------------------------
        // Export all tile layers
        // --------------------------------------------------

        output += "MapData = {\n";


        for (var layerIndex = 0; layerIndex < tileLayers.length; ++layerIndex) {

            var tileLayer = tileLayers[layerIndex];

            var layerName =
                "layer_" +
                String(layerIndex + 1).padStart(2, "0");


            // Layer name
            output += "    " + layerName + " = {\n";


            // --------------------------------------------------
            // Export tile data
            //
            // Tiled:
            // tileId = -1 -> empty
            // tileId =  0  -> first tile
            //
            // TenGine:
            // 0 -> empty
            // 1 -> first tile
            // --------------------------------------------------

            for (var y = 0; y < tileLayer.height; ++y) {

                output += "        {";


                for (var x = 0; x < tileLayer.width; ++x) {

                    var cell = tileLayer.cellAt(x, y);

                    var tileIndex;


                    if (cell.empty) {

                        tileIndex = 0;

                    } else {

                        // Tiled tileId 从 0 开始
                        // TenGine tile index 从 1 开始
                        tileIndex = cell.tileId + 1;

                    }


                    output += tileIndex;


                    if (x < tileLayer.width - 1) {
                        output += ",";
                    }

                }


                output += "}";


                if (y < tileLayer.height - 1) {
                    output += ",";
                }


                output += "\n";

            }


            output += "    }";


            if (layerIndex < tileLayers.length - 1) {
                output += ",";
            }


            output += "\n";

        }


        output += "}\n";


        // --------------------------------------------------
        // Write file
        // --------------------------------------------------

        var file = new TextFile(
            fileName,
            TextFile.WriteOnly
        );

        file.write(output);
        file.commit();

    }
};


// Register TenGine map format
tiled.registerMapFormat(
    "tengine",
    TenGineMapFormat
);